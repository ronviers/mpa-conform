def figure(Ks, a_sp, s_sp, a_at, s_at, Kc_at):
    fig, ax = plt.subplots(1, 2, figsize=(13, 5), dpi=150)
    ax[0].axhline(0, color="gray", lw=0.8)
    ax[0].errorbar(Ks, a_at, yerr=s_at, color="#2e7d32", lw=1.8, marker="o", ms=4,
                   label="attractive (alpha=0): emergent gain")
    ax[0].errorbar(Ks, a_sp, yerr=s_sp, color="#c62828", lw=1.8, marker="s", ms=4,
                   label="splay (alpha=0.9pi): no gain (topological)")
    if Kc_at is not None:
        ax[0].axvline(Kc_at, color="#2e7d32", ls="--", lw=1.2, label=f"K_c ~ {Kc_at:.2f} (gain generated)")
    ax[0].set_xlabel("coupling K"); ax[0].set_ylabel("collective self-gain  a  (rate of ln R)")
    ax[0].set_title("does `a` cross zero un-inserted?  attractive: YES at K_c;\nsplay: NO (a<=0 for all K)")
    ax[0].legend(fontsize=8, frameon=False); ax[0].grid(alpha=0.3)

    # illustrative R(t): attractive above K_c (grows) vs splay (decays)
    rng = np.random.default_rng(7)
    omega = rng.normal(1.0, OMEGA_STD, N)
    Rt_at = run_R(2.5, ALPHA_ATTRACT, omega, seed=1)
    Rt_sp = run_R(2.5, ALPHA_SPLAY, omega, seed=1)
    t = np.arange(len(Rt_at)) * DT
    ax[1].plot(t, Rt_at, color="#2e7d32", lw=1.6, label="attractive K=2.5: R self-amplifies (a>0)")
    ax[1].plot(t, Rt_sp, color="#c62828", lw=1.6, label="splay K=2.5: R decays (a<0)")
    ax[1].axhline(R0, color="gray", ls=":", lw=0.8, label=f"imposed R0={R0}")
    ax[1].set_xlabel("time"); ax[1].set_ylabel("collective coordinate R = |<e^{i th}>|")
    ax[1].set_title("the collective coordinate: GENERATED autonomy (attractive)\nvs restored-to-floor (splay)")
    ax[1].legend(fontsize=8, frameon=False); ax[1].grid(alpha=0.3)

    fig.suptitle("Move 2 (sharpened) -- emergent collective self-gain: generated by coupling (attractive) "
                 "but NOT by the splay (its gain is topological)", fontsize=11, weight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    path = OUT / "emergent_gain.png"
    fig.savefig(path, bbox_inches="tight"); plt.close(fig)
    print(f"\nfigure: {path}")


