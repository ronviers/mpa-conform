N = 200            # units (large -> incoherent floor ~1/sqrt(N) ~ 0.07, well below the R0 we impose)
OMEGA_STD = 0.5    # frequency spread -> finite K_c
DT = 0.01
T = 25.0
R0 = 0.20          # imposed initial coherence (above the floor; in the linear regime)
M_IC = 8           # ICs averaged per (K, alpha)
ALPHA_SPLAY = 0.9 * np.pi
ALPHA_ATTRACT = 0.0


def impose_coherence(rng, R_target):
    """phases from a wrapped-normal with R = exp(-sigma^2/2) = R_target."""
    sigma = float(np.sqrt(max(-2.0 * np.log(R_target), 1e-6)))
    return rng.normal(0.0, sigma, N)


def order_param(theta):
    z = np.mean(np.exp(1j * theta))
    return abs(z), np.angle(z)


def run_R(K, alpha, omega, seed):
    rng = np.random.default_rng(seed)
    theta = impose_coherence(rng, R0) + rng.uniform(0, 2 * np.pi)   # random mean phase
    nsteps = int(T / DT)
    Rt = np.empty(nsteps)
    for k in range(nsteps):
        R, psi = order_param(theta)
        Rt[k] = R
        theta = theta + (omega + K * R * np.sin(psi - theta - alpha)) * DT
    return Rt


def fit_gain(Rt):
    """a = early-time exponential rate of R in the linear window (R in [0.09, 0.32]); slope of ln R vs t."""
    t = np.arange(len(Rt)) * DT
    mask = (Rt > 0.09) & (Rt < 0.32)
    # restrict to the first contiguous run so we read the *initial* drift, not post-saturation wiggles
    if mask.sum() < 8:
        # R left the window almost immediately (fast decay) -> use the first 1.5 time-units
        mask = t < 1.5
    idx = np.where(mask)[0]
    idx = idx[idx <= idx[0] + int(4.0 / DT)]   # cap window length at 4 time-units
    lnR = np.log(np.clip(Rt[idx], 1e-6, None))
    a, _ = np.polyfit(t[idx], lnR, 1)
    return float(a)


def gain_curve(alpha, Ks, omega):
    a_mean, a_std = [], []
    for K in Ks:
        a_ics = [fit_gain(run_R(K, alpha, omega, seed=1000 * int(K * 10) + s)) for s in range(M_IC)]
        a_mean.append(float(np.mean(a_ics))); a_std.append(float(np.std(a_ics)))
    return np.array(a_mean), np.array(a_std)


def zero_crossing(Ks, a):
    """first K where a goes - -> + (linear interp). None if it never crosses up."""
    for i in range(len(Ks) - 1):
        if a[i] <= 0 < a[i + 1]:
            f = (0 - a[i]) / (a[i + 1] - a[i])
            return float(Ks[i] + f * (Ks[i + 1] - Ks[i]))
    return None


